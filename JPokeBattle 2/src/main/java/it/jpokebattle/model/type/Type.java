package it.jpokebattle.model.type;

/**
 * Enumerazione che rappresenta i diversi tipi di Pokémon.
 *
 * I tipi sono usati per determinare l'efficacia delle mosse e delle resistenze dei Pokémon durante il combattimento.
 * Ogni tipo ha interazioni specifiche con altri tipi che influenzano il danno inflitto e ricevuto.
 */
public enum Type {
    NORMAL,
    FIGHTING,
    FLYING,
    POISON,
    GROUND,
    ROCK,
    BUG,
    GHOST,
    FIRE,
    WATER,
    GRASS,
    ELECTRIC,
    PSYCHIC,
    ICE,
    DRAGON,
    STEEL,
    DARK;


}
